// A small seeded generator keeps the rule-based passages reproducible in tests.
function seeded(seed) { return () => { seed = (seed * 1664525 + 1013904223) % 4294967296; return seed / 4294967296; }; }

test('typo hunt protocol accepts only bounded picks, levels, reset, skip and next', () => {
  for (const value of [null, [], {}, { type: 'pick' }, { type: 'pick', index: -1 }, { type: 'pick', index: 1.5 }, { type: 'pick', index: '3' }, { type: 'pick', index: 500 }, { type: 'level', level: 0 }, { type: 'level', level: 6 }, { type: 'level', level: '3' }, { type: 'level', level: 2.5 }, { type: 'mode', mode: 'photo' }, { type: 'score', score: 9999 }]) assert.equal(cleanTypoAction(value), null);
  assert.deepEqual(cleanTypoAction({ type: 'pick', index: 7, correct: true, score: 500 }), { type: 'pick', index: 7 });
  assert.deepEqual(cleanTypoAction({ type: 'level', level: 5, extra: 1 }), { type: 'level', level: 5 });
  assert.deepEqual(cleanTypoAction({ type: 'reset', extra: 1 }), { type: 'reset' });
  assert.deepEqual(cleanTypoAction({ type: 'skip', x: 1 }), { type: 'skip' });
  assert.deepEqual(cleanTypoAction({ type: 'next' }), { type: 'next' });
});

