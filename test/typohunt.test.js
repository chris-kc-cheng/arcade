test('levels 1 to 5 hide exactly that many mistakes in ever longer passages, generated by rules', () => {
  const lengths = {};
  for (let level = 1; level <= 5; level++) {
    for (let seed = 1; seed <= 60; seed++) {
      const puzzle = hunt.generatePuzzle(level, seeded(seed * 7919 + level));
      assert.equal(puzzle.mistakes.length, level, `level ${level} seed ${seed}`);
      assert.equal(puzzle.tokens.length, puzzle.original.length);
      for (const mistake of puzzle.mistakes) {
        assert.ok(hunt.KINDS.includes(mistake.kind));
        assert.equal(puzzle.tokens[mistake.index], mistake.wrong);
        assert.equal(puzzle.original[mistake.index], mistake.right);
        assert.notEqual(mistake.wrong.toLowerCase(), mistake.right.toLowerCase());
      }
      // Only the marked tokens differ from the correct passage, and no two mistakes touch.
      const differing = puzzle.tokens.flatMap((token, index) => token === puzzle.original[index] ? [] : [index]);
      assert.deepEqual(differing, puzzle.mistakes.map(mistake => mistake.index));
      assert.ok(puzzle.mistakes.every((mistake, i) => i === 0 || mistake.index - puzzle.mistakes[i - 1].index > 1));
      lengths[level] = Math.max(lengths[level] || 0, puzzle.tokens.length);
    }
  }
  assert.ok(lengths[1] <= 9 && lengths[5] > lengths[3] && lengths[3] > lengths[1] && lengths[5] >= 40);
});

test('generation varies between rounds and keeps case and punctuation of the original word', () => {
  const titles = new Set(Array.from({ length: 30 }, (_, seed) => hunt.generatePuzzle(3, seeded(seed + 1)).tokens.join(' ')));
  assert.ok(titles.size > 20);
  const [mistake] = hunt.generatePuzzle(1, () => 0).mistakes;
  assert.match(mistake.right, /[A-Za-z]/);
  assert.equal(/[.,?!]$/.test(mistake.right), /[.,?!]$/.test(mistake.wrong));
  assert.equal(mistake.right[0] === mistake.right[0].toUpperCase(), mistake.wrong[0] === mistake.wrong[0].toUpperCase());
});

function started(level = 1, count = 2) {
  const players = ['Ana', 'Bo', 'Cy'].slice(0, count).map((name, i) => hunt.newPlayer(`k${i}`, `hunter-${i + 1}`, name));
  const game = hunt.newGame(level);
  hunt.startRound(game, players, 1000, level);
  assert.equal(game.phase, 'countdown');
  assert.equal(hunt.beginHunt(game, 4000), true);
  return { game, players };
}

test('the server alone judges picks: hits score once, misses deduct points and lock the picker out', () => {
  const { game, players: [a, b] } = started(3);
  const target = game.puzzle.mistakes[0], plain = game.puzzle.tokens.findIndex((_, index) => !game.puzzle.byIndex.has(index));
  assert.deepEqual(hunt.pick(game, b, plain, 4500), { ok: true, hit: false, penalty: hunt.MISS_PENALTY });
  assert.equal(b.misses, 1); assert.equal(b.score, -25, 'a wrong pick deducts points');
  assert.equal(hunt.pick(game, b, target.index, 5000).reason, 'locked');
  const hit = hunt.pick(game, a, target.index, 7000);
  assert.equal(hit.hit, true); assert.ok(hit.points >= hunt.BASE_POINTS + 2 * hunt.LEVEL_BONUS); assert.equal(a.score, hit.points);
  assert.equal(hunt.pick(game, b, target.index, 9000).reason, 'already');
  for (const bad of [-1, 1.2, 9999, '3', NaN, undefined]) assert.equal(hunt.pick(game, a, bad, 9000).ok, false);
});

test('higher levels pay more and wrong picks are never revealed in the shared state', () => {
  const low = started(1), high = started(5);
  high.game.endsAt = low.game.endsAt; // same time bonus, so only the level differs
  const a = hunt.pick(low.game, low.players[0], low.game.puzzle.mistakes[0].index, 5000).points;
  const b = hunt.pick(high.game, high.players[0], high.game.puzzle.mistakes[0].index, 5000).points;
  assert.equal(b - a, 4 * hunt.LEVEL_BONUS);
  const plain = high.game.puzzle.tokens.findIndex((_, index) => !high.game.puzzle.byIndex.has(index));
  const before = JSON.stringify(hunt.publicGame(high.game, 6000));
  hunt.pick(high.game, high.players[1], plain, 6000);
  assert.equal(JSON.stringify(hunt.publicGame(high.game, 6000)), before, 'a miss changes nothing in the public passage state');
});

test('the passage is hidden before play, there is no original copy, and a finished round reveals what was missed', () => {
  assert.equal(hunt.publicGame(hunt.newGame(2), 0).tokens.length, 0);
  const { game, players: [a] } = started(4);
  const view = hunt.publicGame(game, 5000);
  for (const key of ['original', 'mistakes', 'lastMiss', 'mode', 'title']) assert.equal(key in view, false, key);
  assert.deepEqual(view.found, {}); assert.deepEqual(view.missed, []);
  hunt.pick(game, a, game.puzzle.mistakes[0].index, 5000);
  assert.equal(hunt.endHunt(game), true);
  const done = hunt.publicGame(game, 90001);
  assert.equal(done.phase, 'finished'); assert.equal(done.missed.length, 3);
  assert.ok(done.missed.every(item => item.reason.length > 10), 'every missed word explains why it was wrong');
  assert.equal('nextRoundAt' in done, false, 'the next question never starts by itself');
  assert.equal(hunt.pick(game, a, game.puzzle.mistakes[1].index, 90001).ok, false);
});

test('every wrong form in every level carries a specific reason', () => {
  for (let level = 1; level <= 5; level++) for (let seed = 1; seed <= 80; seed++) {
    for (const mistake of hunt.generatePuzzle(level, seeded(seed * 31 + level)).mistakes) {
      assert.ok(mistake.reason && mistake.reason.length > 20, `${mistake.right} > ${mistake.wrong}`);
      assert.ok(!/misspelled\.$|^These words sound alike|^This is not the correct grammar/.test(mistake.reason), `generic reason for ${mistake.right} > ${mistake.wrong}`);
    }
  }
});

test('skipping ends the round for everyone without points, and only a hunting round can be skipped', () => {
  const { game, players: [a, b] } = started(2);
  assert.equal(hunt.skip(game), true);
  assert.equal(game.phase, 'finished'); assert.equal(a.score + b.score, 0);
  const view = hunt.publicGame(game, 9000);
  assert.equal(view.missed.length, 2); assert.ok(view.missed.every(item => item.reason));
  assert.equal(hunt.skip(game), false, 'a finished round cannot be skipped again');
  const waiting = hunt.newGame(1); assert.equal(hunt.skip(waiting), false);
});

test('each player tracks finds in the current round and wrong clicks separately, for the clean-finish celebration', () => {
  const { game, players: [a, b] } = started(2);
  const wrong = game.puzzle.tokens.findIndex((_, index) => !game.puzzle.byIndex.has(index));
  hunt.pick(game, b, wrong, 5000);
  for (const mistake of game.puzzle.mistakes) hunt.pick(game, a, mistake.index, 9000);
  assert.equal(game.phase, 'finished');
  assert.deepEqual([a.roundFound, a.roundMisses, b.roundFound, b.roundMisses], [2, 0, 0, 1]);
  assert.deepEqual([hunt.publicPlayer(a).roundFound, hunt.publicPlayer(a).roundMisses], [2, 0]);
  hunt.startRound(game, [a, b], 20000, 2, { keepScores: true });
  assert.deepEqual([a.roundFound, b.roundMisses, b.misses], [0, 0, 1], 'round counters restart but totals stay');
});

test('finding every mistake ends the round; the next round keeps scores unless reset', () => {
  const { game, players } = started(2);
  const [a] = players;
  for (const mistake of game.puzzle.mistakes) hunt.pick(game, a, mistake.index, 6000);
  assert.equal(game.phase, 'finished'); assert.equal(a.found, 2);
  const kept = a.score;
  hunt.startRound(game, players, 20000, 2, { keepScores: true });
  assert.equal(game.phase, 'countdown'); assert.equal(a.score, kept); assert.equal(game.round, 2); assert.equal(game.found.size, 0);
  hunt.startRound(game, players, 21000, 3);
  assert.equal(a.score, 0); assert.equal(game.level, 3); assert.equal(game.puzzle.mistakes.length, 3);
});

test('a shared room ranks everyone live, changes level for all, and keeps scores across reconnects', async t => {
  const { server, wss } = require('../server');
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const clients = [];
  t.after(async () => { clients.forEach(client => client.terminate()); await new Promise(resolve => wss.close(resolve)); await new Promise(resolve => server.close(resolve)); });
  let arcade = '';
  const join = async label => {
    const states = [], client = new WebSocket(`ws://127.0.0.1:${server.address().port}/?room=typohunt&client=${label}&game=/typohunt${arcade ? `&arcade=${arcade}` : ''}`);
    clients.push(client);
    client.on('message', raw => {
      const message = JSON.parse(raw);
      if (message.type === 'arcadeRooms' && !arcade) arcade = message.currentRoom;
      if (message.type === 'typoState') states.push(message);
    });
    await new Promise(resolve => client.once('open', resolve));
    await waitFor(() => states.length > 0 && arcade);
    return { client, states, last: () => states.at(-1) };
  };
  const self = state => state.players.find(player => player.id === state.selfId);
  const one = await join('hunter-aaaa1111');
  await waitFor(() => one.last().phase === 'hunting', 6000);
  assert.equal(one.last().role, 'player'); assert.equal(one.last().level, 1); assert.equal(one.last().total, 1);
  const two = await join('hunter-bbbb2222'), three = await join('hunter-cccc3333');
  await waitFor(() => three.last().players.length === 3);
  assert.equal(three.last().role, 'player', 'everyone in the room competes');
  assert.equal(JSON.stringify(three.last()).includes('"wrong"'), false);

  // The first player finds the mistake; the others see their ranking and score change live.
  const tokens = one.last().tokens, names = ['Maya', 'Leo', 'Priya', 'Sam', 'Noor', 'Omar', 'Zoe', 'Ben'];
  let target = -1;
  for (const text of hunt.shortSentences) for (const name of names) for (const other of names) {
    const clean = text.replaceAll('{n}', name).replaceAll('{m}', other).split(/\s+/);
    const differing = clean.flatMap((token, index) => token === tokens[index] ? [] : [index]);
    if (clean.length === tokens.length && differing.length === 1) target = differing[0];
  }
  assert.ok(target >= 0, 'the mistake is the one word that differs from a clean sentence');
  const wrongIndex = tokens.findIndex((_, index) => index !== target);
  two.client.send(JSON.stringify({ type: 'pick', index: wrongIndex }));
  await waitFor(() => self(two.last()).score === -hunt.MISS_PENALTY);
  one.client.send(JSON.stringify({ type: 'pick', index: target, score: 99999 }));
  await waitFor(() => one.last().found[target]);
  const scored = self(one.last()).score;
  assert.ok(scored >= hunt.BASE_POINTS && scored < 400, `score ${scored}`);
  await waitFor(() => two.last().players[0].id === one.last().selfId && two.last().players[0].score === scored);
  assert.deepEqual(two.last().players.map(player => player.score), [...two.last().players.map(player => player.score)].sort((a, b) => b - a));

  // The finished round waits for a click: it never rolls into the next question on its own.
  await waitFor(() => three.last().phase === 'finished');
  assert.ok(Object.values(three.last().found).every(item => item.reason));
  await new Promise(resolve => setTimeout(resolve, 400));
  assert.equal(three.last().phase, 'finished'); assert.equal(three.last().round, 1);
  three.client.send(JSON.stringify({ type: 'next' }));
  await waitFor(() => one.last().round === 2 && one.last().phase !== 'finished');
  assert.equal(self(one.last()).score, scored, 'the next question keeps the ranking');
  await waitFor(() => one.last().phase === 'hunting', 6000);
  two.client.send(JSON.stringify({ type: 'next' }));
  await new Promise(resolve => setTimeout(resolve, 150));
  assert.equal(one.last().phase, 'hunting', 'next does nothing while a question is still open');
  three.client.send(JSON.stringify({ type: 'skip' }));
  await waitFor(() => one.last().phase === 'finished');
  assert.equal(one.last().missed.length, 1); assert.ok(one.last().missed[0].reason);

  two.client.send(JSON.stringify({ type: 'level', level: 4 }));
  await waitFor(() => one.last().level === 4 && one.last().total === 4);
  assert.equal(self(one.last()).score, 0, 'changing level restarts the ranking');

  one.client.terminate();
  await waitFor(() => two.last().players.length === 2);
  const back = await join('hunter-aaaa1111');
  await waitFor(() => back.last().players.length === 3 && back.last().role === 'player');
});

async function waitFor(check, timeout = 3000) {
  const end = Date.now() + timeout;
  while (Date.now() < end) { if (check()) return; await new Promise(resolve => setTimeout(resolve, 20)); }
  throw new Error('Timed out waiting for condition');
}

test('the shipped bank holds 500, 400, 300, 200 and 100 distinct, valid questions for levels 1 to 5', () => {
  const expected = { 1: 500, 2: 400, 3: 300, 4: 200, 5: 100 };
  const bank = require('../lib/typohunt-bank.json');
  assert.deepEqual(Object.keys(bank), ['1', '2', '3', '4', '5']);
  for (const level of [1, 2, 3, 4, 5]) {
    assert.equal(bank[level].length, expected[level], `level ${level}`);
    assert.equal(new Set(bank[level].map(entry => JSON.stringify(entry))).size, expected[level], `level ${level} has duplicates`);
    for (const entry of bank[level]) {
      const puzzle = hunt.fromEntry(level, entry), original = entry.text.split(/\s+/);
      assert.equal(puzzle.mistakes.length, level);
      assert.deepEqual(puzzle.tokens.flatMap((token, index) => token === original[index] ? [] : [index]), puzzle.mistakes.map(mistake => mistake.index));
      assert.ok(puzzle.mistakes.every((mistake, i) => i === 0 || mistake.index - puzzle.mistakes[i - 1].index > 1));
      // Every swap is one the rules know to be wrong in place, with a specific explanation.
      const known = hunt.candidates(original);
      for (const mistake of puzzle.mistakes) {
        assert.ok(known.some(candidate => candidate.index === mistake.index && candidate.options.some(option => option.wrong === mistake.wrong && option.kind === mistake.kind)), `${entry.text} @${mistake.index}`);
        assert.ok(mistake.reason.length > 20);
      }
      if (level === 1) assert.ok(original.length <= 9, entry.text);
    }
  }
});

test('questions are dealt from a shuffled deck without repeating until the level is used up', () => {
  hunt.resetDecks();
  const seen = new Set(), random = seeded(5);
  for (let i = 0; i < 200; i++) seen.add(hunt.drawPuzzle(4, random).tokens.join(' '));
  assert.equal(seen.size, 200, 'one full deck contains no repeats');
  assert.equal(hunt.drawPuzzle(4).mistakes.length, 4, 'the deck refills after it is used up');
});

test('the bank mixes many kinds of common learner errors instead of repeating a few favourites', () => {
  const bank = require('../lib/typohunt-bank.json'), pairs = {}, kinds = new Set();
  let total = 0;
  for (const level of [1, 2, 3, 4, 5]) for (const entry of bank[level]) for (const mistake of hunt.fromEntry(level, entry).mistakes) {
    const key = `${mistake.right}>${mistake.wrong}`.replace(/[^A-Za-z'>]/g, '').toLowerCase();
    pairs[key] = (pairs[key] || 0) + 1; kinds.add(mistake.kind); total++;
  }
  assert.ok(Object.keys(pairs).length >= 120, `only ${Object.keys(pairs).length} distinct patterns`);
  assert.ok(Math.max(...Object.values(pairs)) / total < 0.04, 'no single pattern is more than 4% of all mistakes');
  assert.deepEqual([...kinds].sort(), [...hunt.KINDS].sort(), 'every kind of error appears');
});

test('learner errors are only offered where they are certain to be wrong', () => {
  const swap = (text, index) => { const tokens = text.split(' '); return hunt.candidates(tokens).find(candidate => candidate.index === index)?.options.map(option => option.wrong) || []; };
  assert.deepEqual(swap('My sister is taller than me.', 5), [], '"taller than I" is acceptable, so me is never swapped there');
  assert.ok(!swap('They played games after dinner.', 1).includes('play'), 'a bare verb is not certain to be wrong without a past cue');
  assert.ok(swap('They played games yesterday.', 1).includes('play'));
  assert.ok(swap('We have played games.', 2).includes('play'));
  assert.deepEqual(swap('My feet hurt after the walk.', 5), [], '"the walks" is a valid noun plural');
  assert.ok(swap('Class starts on Monday.', 2).includes('in') && !swap('The cat sat on the mat.', 3).includes('in'));
  assert.ok(swap('Maya told Leo a story.', 1).includes('said') && !swap('Maya told a joke.', 1).includes('said'));
  assert.ok(swap("Maya's cat likes fish.", 0).includes('Mayas'));
});
